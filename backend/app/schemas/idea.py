"""Idea-related Pydantic schemas."""

from datetime import datetime
from typing import Optional
from uuid import UUID

from pydantic import BaseModel


class IdeaCreate(BaseModel):
    title: str
    content_type: str
    hook: Optional[str] = None
    angle: Optional[str] = None
    trend_id: Optional[UUID] = None
    key_points: list[str] = []


class IdeaResponse(BaseModel):
    id: UUID
    user_id: UUID
    title: str
    hook: Optional[str] = None
    angle: Optional[str] = None
    content_type: str
    secondary_types: list[str] = []
    score: Optional[float] = None
    estimated_performance: Optional[str] = None
    difficulty: Optional[str] = None
    key_points: list[str] = []
    differentiation: Optional[str] = None
    target_audience_segment: Optional[str] = None
    suggested_publish_window: Optional[str] = None
    trend_connection: Optional[str] = None
    status: str
    trend_id: Optional[UUID] = None
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}


class ContentIdea(BaseModel):
    """Full content idea as generated by the Idea Generator agent."""

    idea_title: str
    hook: str
    angle: str
    content_type: str
    secondary_types: list[str] = []
    trend_connection: Optional[str] = None
    estimated_performance: str
    target_audience_segment: str
    key_points: list[str]
    differentiation: str
    difficulty: str
    suggested_publish_window: str


class IdeaGenerateRequest(BaseModel):
    use_trends: bool = True
    include_evergreen: bool = True
    content_types: list[str] = ["youtube_video", "blog_post", "twitter_thread"]
    count: int = 10


class IdeaUpdateRequest(BaseModel):
    status: Optional[str] = None
    title: Optional[str] = None
    hook: Optional[str] = None
    key_points: Optional[list[str]] = None
